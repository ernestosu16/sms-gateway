// Package backup writes and restores a portable archive of everything a
// gateway installation needs to move to another server: a consistent snapshot
// of the SQLite database and the config file.
package backup

import (
	"archive/tar"
	"compress/gzip"
	"database/sql"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"time"
)

// FormatVersion is bumped when the archive layout changes incompatibly.
const FormatVersion = 1

// Names of the entries inside the archive.
const (
	manifestName = "manifest.json"
	databaseName = "sms-gateway.db"
	configName   = "sms-gateway.conf"
)

// Config sources recorded in the manifest.
const (
	ConfigFromFile      = "file"
	ConfigGenerated     = "generated"
	ConfigNotIncluded   = ""
	fileMode            = 0o600
	generatedConfigHead = "# Generated by `sms-gateway backup` from the settings the gateway was running with.\n" +
		"# Environment variables still take precedence over this file.\n\n"
)

// Manifest describes the contents of an archive.
type Manifest struct {
	FormatVersion int       `json:"format_version"`
	AppVersion    string    `json:"app_version"`
	CreatedAt     time.Time `json:"created_at"`
	DBDriver      string    `json:"db_driver"`
	Database      bool      `json:"database"`
	Config        string    `json:"config"`
}

// CreateOptions configures Create.
type CreateOptions struct {
	// DB is the open SQLite database to snapshot. Nil leaves the database out
	// (for example with PostgreSQL, which is backed up with pg_dump).
	DB       *sql.DB
	DBDriver string
	// ConfigFile is read and archived when it exists.
	ConfigFile string
	// GeneratedConfig is archived when ConfigFile does not exist, so a
	// configuration given only through environment variables (Docker) is kept.
	GeneratedConfig []byte
	AppVersion      string
	Now             time.Time
}

// Create writes a gzipped tar archive to w.
func Create(w io.Writer, opts CreateOptions) (*Manifest, error) {
	now := opts.Now
	if now.IsZero() {
		now = time.Now()
	}
	m := &Manifest{
		FormatVersion: FormatVersion,
		AppVersion:    opts.AppVersion,
		CreatedAt:     now.UTC(),
		DBDriver:      opts.DBDriver,
	}

	var dbFile string
	if opts.DB != nil {
		dir, err := os.MkdirTemp("", "sms-gateway-backup-")
		if err != nil {
			return nil, fmt.Errorf("creating temp dir: %w", err)
		}
		defer os.RemoveAll(dir)

		dbFile = filepath.Join(dir, databaseName)
		// VACUUM INTO writes a consistent, compacted copy even while the server
		// is writing, including changes still held in the WAL.
		if _, err := opts.DB.Exec("VACUUM INTO ?", dbFile); err != nil {
			return nil, fmt.Errorf("snapshotting database: %w", err)
		}
		m.Database = true
	}

	var configData []byte
	if opts.ConfigFile != "" {
		data, err := os.ReadFile(opts.ConfigFile)
		switch {
		case err == nil:
			configData = data
			m.Config = ConfigFromFile
		case !errors.Is(err, os.ErrNotExist):
			return nil, fmt.Errorf("reading config file: %w", err)
		}
	}
	if m.Config == ConfigNotIncluded && len(opts.GeneratedConfig) > 0 {
		configData = append([]byte(generatedConfigHead), opts.GeneratedConfig...)
		m.Config = ConfigGenerated
	}

	gz := gzip.NewWriter(w)
	tw := tar.NewWriter(gz)

	manifestData, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return nil, err
	}
	if err := writeEntry(tw, manifestName, manifestData, m.CreatedAt); err != nil {
		return nil, err
	}
	if dbFile != "" {
		if err := writeFileEntry(tw, databaseName, dbFile, m.CreatedAt); err != nil {
			return nil, err
		}
	}
	if m.Config != ConfigNotIncluded {
		if err := writeEntry(tw, configName, configData, m.CreatedAt); err != nil {
			return nil, err
		}
	}

	if err := tw.Close(); err != nil {
		return nil, fmt.Errorf("writing archive: %w", err)
	}
	if err := gz.Close(); err != nil {
		return nil, fmt.Errorf("writing archive: %w", err)
	}
	return m, nil
}

func writeEntry(tw *tar.Writer, name string, data []byte, modTime time.Time) error {
	hdr := &tar.Header{Name: name, Mode: fileMode, Size: int64(len(data)), ModTime: modTime}
	if err := tw.WriteHeader(hdr); err != nil {
		return fmt.Errorf("writing %s: %w", name, err)
	}
	if _, err := tw.Write(data); err != nil {
		return fmt.Errorf("writing %s: %w", name, err)
	}
	return nil
}

func writeFileEntry(tw *tar.Writer, name, path string, modTime time.Time) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return err
	}
	hdr := &tar.Header{Name: name, Mode: fileMode, Size: info.Size(), ModTime: modTime}
	if err := tw.WriteHeader(hdr); err != nil {
		return fmt.Errorf("writing %s: %w", name, err)
	}
	if _, err := io.Copy(tw, f); err != nil {
		return fmt.Errorf("writing %s: %w", name, err)
	}
	return nil
}
